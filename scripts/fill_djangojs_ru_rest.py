def main() -> None:
    po = polib.pofile(str(PO))
    filled = 0
    missing = []
    for e in po:
        if not e.msgid or e.msgstr:
            continue
        # try exact and unescaped
        ru = T.get(e.msgid)
        if ru is None and "\\n" in e.msgid:
            ru = T.get(e.msgid.replace("\\n", "\n"))
        if ru is None and "\n" in e.msgid:
            ru = T.get(e.msgid.replace("\n", "\\n"))
        if ru:
            e.msgstr = ru
            filled += 1
        else:
            missing.append(e.msgid)
    po.save(str(PO))
    print(f"filled={filled} still_empty={len(missing)}")
    for m in missing[:30]:
        print("MISSING", repr(m[:80]))


if __name__ == "__main__":
    main()
