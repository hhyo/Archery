def _unescape_po(s: str) -> str:
    out: list[str] = []
    i = 0
    while i < len(s):
        if s[i] == "\\" and i + 1 < len(s):
            n = s[i + 1]
            mapping = {"n": "\n", "t": "\t", "r": "\r", '"': '"', "\\": "\\"}
            if n in mapping:
                out.append(mapping[n])
                i += 2
                continue
        out.append(s[i])
        i += 1
    return "".join(out)


def _escape_po(s: str) -> str:
    return (
        s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\t", "\\t")
        .replace("\r", "\\r")
    )


def _parse_entry(block: str) -> tuple[str, str]:
    lines = block.strip().splitlines()
    mid: list[str] = []
    mstr: list[str] = []
    mode = None
    for line in lines:
        if line.startswith("msgid "):
            mode = "id"
            mid.append(
                line[6:].strip()[1:-1] if line[6:].strip().startswith('"') else ""
            )
            # properly extract quoted content
            m = re.match(r'msgid\s+"(.*)"\s*$', line)
            mid = [m.group(1)] if m else [""]
        elif line.startswith("msgstr "):
            mode = "str"
            m = re.match(r'msgstr\s+"(.*)"\s*$', line)
            mstr = [m.group(1)] if m else [""]
        elif line.startswith('"') and mode == "id":
            m = re.match(r'"(.*)"\s*$', line)
            if m:
                mid.append(m.group(1))
        elif line.startswith('"') and mode == "str":
            m = re.match(r'"(.*)"\s*$', line)
            if m:
                mstr.append(m.group(1))
    return _unescape_po("".join(mid)), _unescape_po("".join(mstr))


def _format_msgstr(ru: str) -> str:
    """Format msgstr; use multiline if string contains newlines."""
    if "\n" in ru:
        parts = ru.split("\n")
        # PO convention: empty first line, then each segment
        lines = ['msgstr ""']
        for i, part in enumerate(parts):
            suffix = "\\n" if i < len(parts) - 1 or ru.endswith("\n") else ""
            # if last part empty because trailing newline, still emit
            if i == len(parts) - 1 and part == "" and ru.endswith("\n"):
                break
            if i < len(parts) - 1:
                lines.append(f'"{_escape_po(part)}\\n"')
            else:
                if part or not ru.endswith("\n"):
                    lines.append(f'"{_escape_po(part)}"')
        # Fix for strings ending with newline: last content piece already has \n
        if ru.endswith("\n") and len(parts) >= 1:
            # rebuild cleaner
            lines = ['msgstr ""']
            segs = ru.split("\n")
            # trailing empty from split
            if segs and segs[-1] == "":
                segs = segs[:-1]
                for i, part in enumerate(segs):
                    lines.append(f'"{_escape_po(part)}\\n"')
            else:
                for i, part in enumerate(segs):
                    if i < len(segs) - 1:
                        lines.append(f'"{_escape_po(part)}\\n"')
                    else:
                        lines.append(f'"{_escape_po(part)}"')
        return "\n".join(lines)
    return f'msgstr "{_escape_po(ru)}"'


def fill_po(path: Path, *, force: bool = False) -> tuple[int, int, int]:
    """Return (filled_or_updated, unchanged, still_empty).

    If force=True, overwrite existing msgstr whenever glossary has a translation.
    """
    text = path.read_text(encoding="utf-8")
    filled_now = 0
    unchanged = 0
    still_empty = 0
    missing: list[str] = []

    def repl(match: re.Match) -> str:
        nonlocal filled_now, unchanged, still_empty
        block = match.group(0)
        msgid, msgstr = _parse_entry(block)
        if not msgid:
            return block  # header
        ru = GLOSSARY.get(msgid)
        if not ru:
            if msgstr:
                unchanged += 1
            else:
                still_empty += 1
                missing.append(msgid)
            return block
        if msgstr and not force and msgstr == ru:
            unchanged += 1
            return block
        if msgstr and not force:
            unchanged += 1
            return block
        if msgstr == ru:
            unchanged += 1
            return block
        filled_now += 1
        msgid_part = re.match(
            r'(msgid (?:"(?:\\.|[^"\\])*"' r'(?:\s*"(?:\\.|[^"\\])*")*)\s*)',
            block,
        )
        if not msgid_part:
            still_empty += 1
            filled_now -= 1
            missing.append(msgid)
            return block
        return msgid_part.group(1) + _format_msgstr(ru)

    new_text = ENTRY_RE.sub(repl, text)
    path.write_text(new_text, encoding="utf-8")
    if missing:
        print(f"  MISSING ({len(missing)}):")
        for m in missing[:20]:
            print(f"    {m!r}")
        if len(missing) > 20:
            print(f"    ... and {len(missing) - 20} more")
    return filled_now, unchanged, still_empty


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("po_files", nargs="*")
    parser.add_argument(
        "--targets", action="store_true", help="Fill the three target RU PO files"
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite existing msgstr with glossary values",
    )
    parser.add_argument("--check-coverage", action="store_true")
    args = parser.parse_args()

    if args.check_coverage:
        # report which msgids in targets are not in glossary
        from collections import Counter

        def decode(block: str) -> str:
            chunks = []
            for m in re.finditer(r'"((?:\\.|[^"\\])*)"', block):
                chunks.append(_unescape_po(m.group(1)))
            return "".join(chunks)

        missing = []
        for path in TARGETS:
            text = path.read_text(encoding="utf-8")
            for m in ENTRY_RE.finditer(text):
                mid, mstr = _parse_entry(m.group(0))
                if mid and mid not in GLOSSARY:
                    missing.append(mid)
        print(f"msgids not in glossary: {len(set(missing))}")
        for m in sorted(set(missing)):
            print(repr(m))
        return

    files: list[Path] = []
    if args.targets:
        files = TARGETS
    else:
        files = [Path(p) for p in args.po_files]

    print(f"Glossary size: {len(GLOSSARY)}")
    for f in files:
        filled, unchanged, empty = fill_po(f, force=args.force)
        total = filled + unchanged + empty
        pct = (100.0 * (filled + unchanged) / total) if total else 0
        print(
            f"{f.relative_to(ROOT)}: updated={filled}, "
            f"unchanged={unchanged}, empty={empty}, total={total}, coverage={pct:.1f}%"
        )


if __name__ == "__main__":
    main()
